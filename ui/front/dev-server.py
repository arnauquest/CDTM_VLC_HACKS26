#!/usr/bin/env python3
"""Servidor estático de desarrollo SIN caché (evita ver módulos JS antiguos).

Uso:  python3 dev-server.py [puerto]      (por defecto 5173)
Sirve el directorio donde está este archivo.
"""
import functools
import http.server
import os
import sys


class NoCacheHandler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {**http.server.SimpleHTTPRequestHandler.extensions_map, ".js": "text/javascript", ".svg": "image/svg+xml"}

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()


if __name__ == "__main__":
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 5173
    root = os.path.dirname(os.path.abspath(__file__))
    handler = functools.partial(NoCacheHandler, directory=root)
    with http.server.ThreadingHTTPServer(("127.0.0.1", port), handler) as httpd:
        print(f"Sirviendo {root} en http://localhost:{port}")
        httpd.serve_forever()
